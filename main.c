static unsigned char *decodeFont(int *length){
    const char *src=embeddedFont64;
    int cap=(int)strlen(src)*3/4+3;
    unsigned char *out=(unsigned char *)malloc((size_t)cap);
    if(!out)return NULL;
    unsigned int accum=0;
    int bits=-8,pos=0;
    for(;*src && *src!='=';src++){
        int v;
        if(*src>='A'&&*src<='Z')v=*src-'A';
        else if(*src>='a'&&*src<='z')v=*src-'a'+26;
        else if(*src>='0'&&*src<='9')v=*src-'0'+52;
        else if(*src=='+')v=62;
        else if(*src=='/')v=63;
        else continue;
        accum=(accum<<6)|v;
        bits+=6;
        if(bits>=0){out[pos++]=(unsigned char)((accum>>bits)&255);bits-=8;}
    }
    *length=pos;
    return out;
}



