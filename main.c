static bool inBounds(int r,int c){return r>=0&&r<n&&c>=0&&c<n;}
/* Define cinco orientacoes sorteadas, mas exige variedade real.
   Facil: pelo menos uma horizontal e uma vertical.
   Medio: horizontal, vertical e as duas diagonais.
   Dificil: horizontal, vertical, diagonal, inversa reta e inversa diagonal.
   O sorteio das orientacoes e redistribuido entre as cinco palavras. */
static void chooseDirections(int assigned[COUNT]){
    if(level==0){
        assigned[0]=0; assigned[1]=1;
        for(int i=2;i<COUNT;i++)assigned[i]=GetRandomValue(0,1);
    }else if(level==1){
        assigned[0]=0;assigned[1]=1;assigned[2]=2;assigned[3]=3;
        assigned[4]=GetRandomValue(0,3);
    }else{
        assigned[0]=0;assigned[1]=1;
        assigned[2]=GetRandomValue(2,3);
        assigned[3]=GetRandomValue(4,5);
        assigned[4]=GetRandomValue(6,7);
    }
    for(int i=COUNT-1;i>0;i--){
        int j=GetRandomValue(0,i);
        int tmp=assigned[i];assigned[i]=assigned[j];assigned[j]=tmp;
    }
}
static bool place(int i,int d){
    const char *s=words[level][i].word;
    int len=(int)strlen(s);
    int dr=dirs[d][0],dc=dirs[d][1];
    for(int attempt=0;attempt<800;attempt++){
        int r=GetRandomValue(0,n-1),c=GetRandomValue(0,n-1);
        if(!inBounds(r+(len-1)*dr,c+(len-1)*dc))continue;
        bool fits=true;
        for(int k=0;k<len;k++){
            char v=grid[r+k*dr][c+k*dc];
            if(v!='.' && v!=s[k]){fits=false;break;}
        }
        if(!fits)continue;
        pos[i]=(Position){r,c,dr,dc};
        for(int k=0;k<len;k++)grid[r+k*dr][c+k*dc]=s[k];
        return true;
    }
    return false;
}
static void initLevel(int chosen){
    level=chosen;n=sizes[level];target=0;dragging=false;sr=sc=er=ec=-1;
    bool ok;
    do{
        int assigned[COUNT];
        chooseDirections(assigned);
        for(int r=0;r<n;r++)for(int c=0;c<n;c++)grid[r][c]='.';
        ok=true;
        /* Posicionar primeiro as palavras longas melhora o encaixe. */
        for(int i=0;i<COUNT;i++)if(!place(i,assigned[i])){ok=false;break;}
    }while(!ok);
    for(int r=0;r<n;r++)for(int c=0;c<n;c++)
        if(grid[r][c]=='.')grid[r][c]='A'+GetRandomValue(0,25);
    for(int i=0;i<COUNT;i++){solved[i]=false;order[i]=i;}
    for(int i=COUNT-1;i>0;i--){
        int j=GetRandomValue(0,i);
        int tmp=order[i];order[i]=order[j];order[j]=tmp;
    }
    screen=PLAY;
}
static bool getCell(Vector2 m,int *r,int *c){
    if(m.x<BX||m.y<BY||m.x>=BX+n*CELL||m.y>=BY+n*CELL)return false;
    *r=(int)(m.y-BY)/CELL;*c=(int)(m.x-BX)/CELL;
    return true;
}
static bool selected(int r,int c){
    if(!dragging||sr<0||er<0)return false;
    int dy=er-sr,dx=ec-sc;
    if(dy&&dx&&abs(dy)!=abs(dx))return false;
    int steps=abs(dy)>abs(dx)?abs(dy):abs(dx);
    int dr=(dy>0)-(dy<0),dc=(dx>0)-(dx<0);
    for(int k=0;k<=steps;k++)if(r==sr+k*dr&&c==sc+k*dc)return true;
    return false;
}
static void checkWord(void){
    if(target>=COUNT||er<0)return;
    int wordId=order[target];
    Position p=pos[wordId];
    int len=(int)strlen(words[level][wordId].word);
    int endr=p.r+(len-1)*p.dr,endc=p.c+(len-1)*p.dc;
    bool match=(sr==p.r&&sc==p.c&&er==endr&&ec==endc)||
               (er==p.r&&ec==p.c&&sr==endr&&sc==endc);
    if(match){
        explained=wordId;
        solved[wordId]=true;
        score+=prizes[level];
        target++;
        screen=EXPLAIN;
    }
}
