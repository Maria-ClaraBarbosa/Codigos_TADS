/* Mostra uma explicacao apos cada acerto. As linhas sao quebradas
   conforme a largura disponivel, evitando texto fora do painel. */
static void paragraph(const char *s, int x, int y, int maxWidth, int fontSize, int lineHeight, Color color){
    char line[260]="";
    char word[100];
    int count=0, row=0;
    while(*s){
        while(*s==' ')s++;
        if(!*s)break;
        count=0;
        while(*s && *s!=' ' && count<(int)sizeof(word)-1)word[count++]=*s++;
        word[count]='\0';
        char test[260];
        snprintf(test,sizeof(test),"%s%s%s",line,line[0]?" ":"",word);
        if(line[0] && MeasureTextEx(font,test,(float)fontSize,1).x>maxWidth){
            txt(line,x,y+row*lineHeight,(float)fontSize,color);
            row++;
            snprintf(line,sizeof(line),"%s",word);
        }else{
            snprintf(line,sizeof(line),"%s",test);
        }
    }
    if(line[0])txt(line,x,y+row*lineHeight,(float)fontSize,color);
}
